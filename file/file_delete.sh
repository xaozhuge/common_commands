# 1. 文件名特殊 (含特殊字符、换行、不可见字符、`-`开头、中文乱码等), 无法直接 `rm 文件名` 删除
# 改用 inode (i 节点号)定位删除, inode 是文件系统里文件 / 目录唯一编号, 不受文件名干扰

# 2. i: 打印 inode 号
ls -lid

# 3. 先预览, 确认这个 inode 对应的是不是你要删的文件 / 目录, 这一步一定要先执行
# .: 在当前目录开始查找
# maxdepth 1: 只查当前目录, 不递归进入子目录(非常关键, 避免误删子目录里同 inode 硬链接)
# -inum 2891604: 匹配 inode 等于 2891604 的对象
find . -maxdepth 1 -inum 2891604

# 4. 文件删除
# -delete: find 内置删除动作
find . -maxdepth 1 -inum 2891604 -delete

